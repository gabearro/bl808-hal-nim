## Supported SIMD binary-to-IR opcode mapping. Zero means unsupported.
import types

func simdOpcode*(subOpcode: uint32): uint16 =
  case subOpcode
  of 0: uint16(ord(opV128Load))
  of 11: uint16(ord(opV128Store))
  of 12: uint16(ord(opV128Const))
  of 15: uint16(ord(opI8x16Splat))
  of 16: uint16(ord(opI16x8Splat))
  of 17: uint16(ord(opI32x4Splat))
  of 18: uint16(ord(opI64x2Splat))
  of 19: uint16(ord(opF32x4Splat))
  of 20: uint16(ord(opF64x2Splat))
  of 21: uint16(ord(opI8x16ExtractLaneS))
  of 22: uint16(ord(opI8x16ExtractLaneU))
  of 23: uint16(ord(opI8x16ReplaceLane))
  of 24: uint16(ord(opI16x8ExtractLaneS))
  of 25: uint16(ord(opI16x8ExtractLaneU))
  of 26: uint16(ord(opI16x8ReplaceLane))
  of 27: uint16(ord(opI32x4ExtractLane))
  of 28: uint16(ord(opI32x4ReplaceLane))
  of 29: uint16(ord(opI64x2ExtractLane))
  of 30: uint16(ord(opI64x2ReplaceLane))
  of 31: uint16(ord(opF32x4ExtractLane))
  of 32: uint16(ord(opF32x4ReplaceLane))
  of 33: uint16(ord(opF64x2ExtractLane))
  of 34: uint16(ord(opF64x2ReplaceLane))
  of 77: uint16(ord(opV128Not))
  of 78: uint16(ord(opV128And))
  of 79: uint16(ord(opV128AndNot))
  of 80: uint16(ord(opV128Or))
  of 81: uint16(ord(opV128Xor))
  of 96: uint16(ord(opI8x16Abs))
  of 97: uint16(ord(opI8x16Neg))
  of 110: uint16(ord(opI8x16Add))
  of 113: uint16(ord(opI8x16Sub))
  of 118: uint16(ord(opI8x16MinS))
  of 119: uint16(ord(opI8x16MinU))
  of 120: uint16(ord(opI8x16MaxS))
  of 121: uint16(ord(opI8x16MaxU))
  of 128: uint16(ord(opI16x8Abs))
  of 129: uint16(ord(opI16x8Neg))
  of 142: uint16(ord(opI16x8Add))
  of 145: uint16(ord(opI16x8Sub))
  of 149: uint16(ord(opI16x8Mul))
  of 160: uint16(ord(opI32x4Abs))
  of 161: uint16(ord(opI32x4Neg))
  of 171: uint16(ord(opI32x4Shl))
  of 172: uint16(ord(opI32x4ShrS))
  of 173: uint16(ord(opI32x4ShrU))
  of 174: uint16(ord(opI32x4Add))
  of 177: uint16(ord(opI32x4Sub))
  of 181: uint16(ord(opI32x4Mul))
  of 182: uint16(ord(opI32x4MinS))
  of 183: uint16(ord(opI32x4MinU))
  of 184: uint16(ord(opI32x4MaxS))
  of 185: uint16(ord(opI32x4MaxU))
  of 206: uint16(ord(opI64x2Add))
  of 209: uint16(ord(opI64x2Sub))
  of 224: uint16(ord(opF32x4Abs))
  of 225: uint16(ord(opF32x4Neg))
  of 228: uint16(ord(opF32x4Add))
  of 229: uint16(ord(opF32x4Sub))
  of 230: uint16(ord(opF32x4Mul))
  of 231: uint16(ord(opF32x4Div))
  of 236: uint16(ord(opF64x2Abs))
  of 237: uint16(ord(opF64x2Neg))
  of 240: uint16(ord(opF64x2Add))
  of 241: uint16(ord(opF64x2Sub))
  of 242: uint16(ord(opF64x2Mul))
  of 243: uint16(ord(opF64x2Div))
  else: 0
